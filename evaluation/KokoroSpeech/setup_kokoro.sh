#!/usr/bin/env bash
# Download and prepare Kokoro Speech Dataset for evaluation.
#
# Usage:
#   bash setup_kokoro.sh            # tiny (default, 308 clips)
#   bash setup_kokoro.sh small      # small (9199 clips)
#   bash setup_kokoro.sh large      # large (23461 clips)
#
# Result layout (relative to this script):
#   metadata.csv        ← pipe-delimited: ID|Transcription|Reading
#   KokoroSpeech/       ← WAV files at 22050 Hz (resampled to 16 kHz by test script)
#
# Requirements: git, python3, pip, librosa, soundfile

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SIZE="${1:-tiny}"
TMP_DIR="$(mktemp -d)"
REPO_URL="https://github.com/kaiidams/Kokoro-Speech-Dataset.git"

echo "=== Kokoro Speech Dataset setup (size: $SIZE) ==="
echo "Dest: $SCRIPT_DIR"
echo "Tmp:  $TMP_DIR"
echo ""

cleanup() { rm -rf "$TMP_DIR"; }
trap cleanup EXIT

# ── 1. Clone repo ──────────────────────────────────────────────────────────
echo "[1/5] Cloning Kokoro-Speech-Dataset..."
git clone --depth 1 "$REPO_URL" "$TMP_DIR/repo"
cd "$TMP_DIR/repo"

# ── 2. Download metadata zip (contains index.json + metadata.csv) ──────────
echo "[2/5] Downloading metadata from GitHub releases..."
mkdir -p data
curl -L -o data/kokoro-speech-v1_3.zip \
  https://github.com/kaiidams/Kokoro-Speech-Dataset/releases/download/1.3/kokoro-speech-v1_3.zip
python3 -m zipfile -e data/kokoro-speech-v1_3.zip data/

echo "  Extracted files in data/:"
find data -maxdepth 3 -type f | sort

if [ ! -f "data/index.json" ]; then
  echo "ERROR: data/index.json not found after unzipping"
  exit 1
fi
echo "  data/index.json OK"

# ── 3. Install librosa + soundfile (torchaudio/torchcodec not needed) ─────
echo "[3/5] Installing librosa + soundfile..."
pip install librosa soundfile --quiet

# ── 4. Download MP3 source files ───────────────────────────────────────────
# extract.py prints shell commands including `unzip X -d Y`.
# sed transforms those to `python3 -m zipfile -e X Y` since unzip may not be installed.
echo "[4/5] Downloading MP3 files from archive.org..."
set +e
python3 extract.py --size "$SIZE" 2>/dev/null \
  | sed -E 's/^unzip +([^ ]+\.zip) +-d +(.+)$/python3 -m zipfile -e \1 \2/' \
  | grep -E '^(wget |curl |mkdir |cd |python3 )' \
  | bash
set -e
echo "  MP3 download step done"

# ── 5. Extract WAV clips (librosa backend, no torchaudio/torchcodec needed) ─
echo "[5/5] Extracting WAV clips to output/..."
python3 "$SCRIPT_DIR/extract_librosa.py" --size "$SIZE"

# ── Copy to evaluation directory ──────────────────────────────────────────
echo ""
echo "Copying files..."

# metadata.csv is generated by extract_librosa.py at output/metadata.csv
if [ ! -f "output/metadata.csv" ]; then
  echo "ERROR: output/metadata.csv not found — extraction may have failed"
  exit 1
fi
cp output/metadata.csv "$SCRIPT_DIR/metadata.csv"

mkdir -p "$SCRIPT_DIR/KokoroSpeech"
WAV_COUNT=$(find output/wavs -name "*.wav" 2>/dev/null | wc -l)
if [ "$WAV_COUNT" -eq 0 ]; then
  echo "ERROR: No WAV files found in output/wavs/"
  echo "The extraction step may have failed. Check the output above for errors."
  exit 1
fi
find output/wavs -name "*.wav" -exec cp {} "$SCRIPT_DIR/KokoroSpeech/" \;

echo ""
echo "=== Done ==="
echo "Copied $WAV_COUNT WAV files → $SCRIPT_DIR/KokoroSpeech/"
echo "metadata.csv              → $SCRIPT_DIR/metadata.csv"
echo ""
echo "Next step:"
echo "  python evaluation/KokoroSpeech/test_qwen3_kokoro.py \\"
echo "    --model baseline(1.0.0) --scope sample --limit 50"
